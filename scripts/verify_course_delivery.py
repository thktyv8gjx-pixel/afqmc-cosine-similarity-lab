"""Teacher entry: A synthetic (default), B prepare, C train, D frozen.

A: original 49 tests + 37 preparation tests + delivery regressions + toy cosine.
B: official download/audit and exact full Manifest; no model evaluation.
C: explicit internal Train run in a new private directory; never overwrite outputs.
D: frozen bytes and saved aggregate arithmetic; no official Dev replay.
Reports/template are private external prerequisites, never generated by this CLI.
"""
from __future__ import annotations
import argparse
from datetime import datetime, timezone
from pathlib import Path
import sys
import uuid

from course_delivery import (ROOT, DeliveryError, environment, lock_path, new_output, no_symlink,
                             run_logged, verify_frozen, write_json_new)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--mode', choices=['synthetic', 'prepare', 'train', 'frozen'], default='synthetic')
    p.add_argument('--root', type=Path, default=ROOT, help='Source/data root; independent of current directory')
    p.add_argument('--output', type=Path, help='Must not exist; Train requires a path below ROOT/local_delivery')
    p.add_argument('--offline', action='store_true', help='Preparation: never use the network')
    p.add_argument('--font', type=Path, help='Train-only legally installed CJK font')
    p.add_argument('--print-lock', action='store_true', help='Print the native platform hash-lock path and exit')
    a = p.parse_args(argv)
    if a.offline and a.mode != 'prepare':
        p.error('--offline is only valid with --mode prepare')
    if a.font and a.mode != 'train':
        p.error('--font is only valid with --mode train')
    if a.mode == 'train' and a.output is None:
        p.error('Train requires --output local_delivery/<new-directory>')
    output = None
    record = {'passed': False, 'mode': a.mode, 'dev_evaluation': False,
              'started_utc': datetime.now(timezone.utc).isoformat(), 'checks': []}
    try:
        if a.print_lock:
            print(lock_path()); return 0
        root = a.root.resolve()
        if a.mode == 'train':
            no_symlink(a.output.absolute())
            candidate = a.output.resolve()
            private = root / 'local_delivery'
            if candidate == private or not candidate.is_relative_to(private):
                raise DeliveryError('Train output must be a new directory below ROOT/local_delivery (private, ignored)')
        output = new_output(a.output or root / 'course_validation' / (datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S') + '-' + uuid.uuid4().hex[:8]))
        record['environment'] = environment()
        record['frozen'] = verify_frozen(root)
        checks = record['checks']
        checks.append(run_logged('pip-check', ['-m', 'pip', 'check'], root, output))
        if checks[-1]['exit_code']:
            raise DeliveryError('pip check failed; see local log')
        if a.mode == 'synthetic':
            commands = [('synthetic', ['scripts/check_afqmc_synthetic.py'], None),
                        ('preparation-tests', ['scripts/test_prepare_afqmc.py'], 37),
                        ('delivery-tests', ['-m', 'unittest', 'discover', '-s', 'tests', '-v'], None)]
            for name, args, expected in commands:
                item = run_logged(name, args, root, output); checks.append(item)
                if item['exit_code'] or (expected is not None and item.get('tests_run') != expected):
                    raise DeliveryError(f'{name} failed or expected test count missing; see local log')
                if name == 'delivery-tests' and item.get('tests_run', 0) == 0:
                    raise DeliveryError('No delivery regression tests were discovered')
            original = checks[1]['result']['runs'][0]['result']
            if original['tests_run'] != 49 or not original['passed']:
                raise DeliveryError('Original synthetic suite did not pass all 49 tests')
        elif a.mode == 'prepare':
            from prepare_afqmc import prepare, PreparationError
            try:
                record['preparation'] = prepare(root, offline=a.offline)
                if not a.offline:
                    from course_delivery import sha
                    paths = [root / 'stage01_data_audit/raw/afqmc_public.zip', root / 'stage01_data_audit/split_manifest.csv']
                    before = [(sha(x), x.stat().st_mtime_ns) for x in paths]
                    record['offline_recheck'] = prepare(root, offline=True)
                    record['idempotent_bytes_and_mtime'] = before == [(sha(x), x.stat().st_mtime_ns) for x in paths]
                    if not record['idempotent_bytes_and_mtime']:
                        raise DeliveryError('Offline preparation changed existing inputs')
            except PreparationError as error:
                raise DeliveryError(str(error)) from None
        elif a.mode == 'train':
            from run_course_train import run_train
            record['train'] = run_train(root, output, a.font)
        record['frozen_after'] = verify_frozen(root)
        record['passed'] = True
    except DeliveryError as error:
        record['error'] = str(error)
    except Exception as error:
        record['error'] = f'{type(error).__name__}: check local permissions and required files; no record contents logged'
    record['exit_code'] = 0 if record['passed'] else 2
    record['finished_utc'] = datetime.now(timezone.utc).isoformat()
    if output is not None:
        write_json_new(output / 'summary.json', record)
    import json
    print(json.dumps(record, ensure_ascii=False, indent=2))
    return record['exit_code']

if __name__ == '__main__':
    raise SystemExit(main())
